#!/usr/bin/env node
/**
 * Request 51: the Word templates for alerts and newsletters ("Alert
 * Template.docx" and "Newsletter Template.docx" at the root of the repo) as a
 * module the API worker can read (it has no file system). Each template's
 * parts are unpacked here, so the worker fills in the XML and packs the
 * .docx again without needing to inflate anything.
 *
 *   node scripts/build-docx-templates.mjs           write the module (only if it changed)
 *   node scripts/build-docx-templates.mjs --check   fail if the module is out of date
 *
 * Run it (or deploy the API, which runs it first) after changing a template.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { inflateRawSync } from "node:zlib";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "apps/api/src/templates/docxTemplates.generated.ts");
const TEMPLATES = [
  { name: "ALERT_TEMPLATE", file: "Alert Template.docx" },
  { name: "NEWSLETTER_TEMPLATE", file: "Newsletter Template.docx" },
];

/** The entries of a .docx (a ZIP file), read from its central directory. */
function unzip(buf) {
  let eocd = -1;
  for (let i = buf.length - 22; i >= 0; i--) if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  if (eocd < 0) throw new Error("Not a .docx (no ZIP directory)");
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const out = [];
  for (let n = 0; n < count; n++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error("Bad ZIP directory");
    const method = buf.readUInt16LE(p + 10);
    const size = buf.readUInt32LE(p + 20);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const local = buf.readUInt32LE(p + 42);
    const name = buf.subarray(p + 46, p + 46 + nameLen).toString("utf8");
    const start = local + 30 + buf.readUInt16LE(local + 26) + buf.readUInt16LE(local + 28);
    const raw = buf.subarray(start, start + size);
    const data = method === 0 ? raw : method === 8 ? inflateRawSync(raw) : null;
    if (!data) throw new Error(`Unsupported compression in ${name}`);
    if (!name.endsWith("/")) out.push({ name, data });
    p += 46 + nameLen + extraLen + commentLen;
  }
  return out;
}

const isText = (name) => /\.(xml|rels)$/i.test(name);

/** Word's revision-session IDs: bookkeeping only, and most of the template's size (Word rebuilds them). */
const slim = (name, xml) => (name === "word/settings.xml" ? xml.replace(/<w:rsids>[\s\S]*?<\/w:rsids>/, "") : xml).replace(/ w:rsid\w*="[0-9A-Fa-f]{8}"/g, "");

let body = "";
for (const t of TEMPLATES) {
  const src = readFileSync(path.join(root, t.file));
  const sha = createHash("sha256").update(src).digest("hex");
  const parts = unzip(src)
    .map((e) => (isText(e.name) ? `  { name: ${JSON.stringify(e.name)}, text: ${JSON.stringify(slim(e.name, e.data.toString("utf8")))} },` : `  { name: ${JSON.stringify(e.name)}, b64: ${JSON.stringify(e.data.toString("base64"))} },`))
    .join("\n");
  body += `\n/** ${t.file} (sha256 ${sha}). */\nexport const ${t.name}: TemplatePart[] = [\n${parts}\n];\n`;
}
const out = `// Generated by scripts/build-docx-templates.mjs from the .docx templates at the root of the repo. Do not edit.
export interface TemplatePart {
  name: string;
  /** XML parts, as text. */
  text?: string;
  /** Other parts (images), base64. */
  b64?: string;
}
${body}`;

const check = process.argv.includes("--check");
const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (current === out) process.exit(0);
if (check) {
  console.error("apps/api/src/templates/docxTemplates.generated.ts is out of date: run `node scripts/build-docx-templates.mjs`.");
  process.exit(1);
}
writeFileSync(OUT, out);
console.log(`Wrote ${path.relative(root, OUT)}`);
